export type Subject = {
  /** NEIS가 준 이름 그대로 */
  raw: string;
  /** [보강] 같은 표시를 뗀 이름 */
  name: string;
  /** 한 주 보기 칸에 넣을 짧은 이름 */
  short: string;
  group: SubjectGroup;
  /** 보강 수업이면 true */
  makeup: boolean;
  /** 수업이 아니라 휴일이면 true (추석처럼 교시마다 채워져 들어와요) */
  holiday: boolean;
};

