/** 이름 앞뒤에 붙는 군더더기. 뜻을 바꾸지 않아서 떼어내도 돼요. */
const NOISE = /^(공통|통합|심화|일반|기본)\s*/;
/** 끝에 붙는 학년·학기 숫자와 로마 숫자 (공통국어2, 미적분Ⅰ) */
const LEVEL = /\s*[0-9ⅠⅡⅢⅣⅤ]+$/;

/** [보강], (보강) 같은 표시를 떼요. 뗀 자리에 보강이었다는 사실만 남겨요. */
const MAKEUP = /^\s*[[(【]\s*보강\s*[\])】]\s*/;

function groupOf(name: string): SubjectGroup {
  for (const [group, words] of RULES) {
    if (words.some((w) => name.includes(w))) return group;
  }
  return '기타';
}

function shortOf(name: string): string {
  if (SHORT[name]) return SHORT[name];

  // 군더더기를 떼고 다시 찾아봐요. "과학탐구실험2" -> "과학탐구실험" -> "과탐"
  const bare = name.replace(NOISE, '').replace(LEVEL, '').trim();
  if (SHORT[bare]) return SHORT[bare];
  if (bare.length <= 4) return bare || name;

  // 그래도 길면 첫 낱말만. "스포츠 생활" -> "스포츠"
  const first = bare.split(/[\s·]/)[0];
  if (first.length <= 4) return first;

  return bare.slice(0, 3);
}

/** NEIS 과목 이름 하나를 읽어요. */
export function readSubject(raw: string): Subject {
  const trimmed = raw.trim();
  const makeup = MAKEUP.test(trimmed);
  const name = trimmed.replace(MAKEUP, '').trim();
  const group = groupOf(name);

  return {
    raw: trimmed,
    name,
    short: shortOf(name),
    group,
    makeup,
    holiday: group === '휴일',
  };
}

/** 과목 이름만 주면 교과군을 알려줘요. 색·아이콘 고를 때 써요. */
export function subjectGroup(raw: string): SubjectGroup {
  return readSubject(raw).group;
}

/**
 * 하루치 수업이 통째로 휴일인지 봐요.
 * NEIS는 추석 같은 날에도 1교시부터 끝까지 "추석"으로 채워서 줘요.
 * 그대로 그리면 "1교시 추석, 2교시 추석..." 이 돼버려요.
 */
export function holidayName(subjects: string[]): string | null {
  if (subjects.length === 0) return null;
  const read = subjects.map(readSubject);
  if (!read.every((s) => s.holiday)) return null;
  return read[0].name;
}
