/*
 * 조사가 제대로 붙는지 재요.
 *
 *   deno run --allow-read --sloppy-imports scripts/check-korean.ts
 *
 * 화면에 나오는 이름은 우리가 정하는 게 아니에요. NEIS가 주는 과목 이름,
 * 학생이 적은 메일 주소가 그대로 들어와요. 그래서 아무 글자로 끝나도
 * 어색하지 않아야 해요.
 */
import { eul, eun, i, ro, wa } from '@/lib/korean';

const fails: string[] = [];
const ok = (got: string, want: string, m: string) => {
  const good = got === want;
  console.log(`${good ? '  통과' : '  실패'}  ${m} → ${got}${good ? '' : ` (${want} 여야 해요)`}`);
  if (!good) fails.push(m);
};

console.log('\n=== 로 / 으로 ===');
ok('수학' + ro('수학'), '수학으로', '수학');          // ㄱ 받침
ok('기하' + ro('기하'), '기하로', '기하');            // 받침 없음
ok('미적분Ⅰ' + ro('미적분Ⅰ'), '미적분Ⅰ로', '미적분Ⅰ'); // 로마숫자로 끝남
ok('체육' + ro('체육'), '체육으로', '체육');
ok('과학' + ro('과학'), '과학으로', '과학');
ok('사회' + ro('사회'), '사회로', '사회');
ok('국어' + ro('국어'), '국어로', '국어');
ok('한글' + ro('한글'), '한글로', '한글');            // ㄹ 받침은 '로'
ok('서울' + ro('서울'), '서울로', '서울');
ok('정보' + ro('정보'), '정보로', '정보');

console.log('\n=== 영문·숫자로 끝날 때 ===');
ok('2반' + ro('2반'), '2반으로', '2반');
ok('3' + ro('3'), '3으로', '3');                            // 삼
ok('2' + ro('2'), '2로', '2');                              // 이
ok('B' + ro('B'), 'B로', 'B');                              // 비
ok('L' + ro('L'), 'L로', 'L');                              // 엘 (ㄹ 받침이라 '로')
ok('M' + ro('M'), 'M으로', 'M');                            // 엠

/*
 * 메일 주소에는 조사를 붙이지 않아요.
 *
 * 글자 하나하나로 읽으면 '.net'은 '티'로 끝나서 '로'가 맞아요. 그런데 사람은
 * '넷'이라고 읽어요. 그러면 '으로'가 맞죠. 어느 쪽으로 정해도 절반은 어색해요.
 * 그래서 주소 뒤에는 조사를 안 붙이고 줄을 나눠서 보여줘요 (start.tsx).
 */

console.log('\n=== 을 / 를, 이 / 가, 은 / 는, 와 / 과 ===');
ok('수학' + eul('수학'), '수학을', '수학');
ok('기하' + eul('기하'), '기하를', '기하');
ok('선생님' + i('선생님'), '선생님이', '선생님');
ok('학교' + i('학교'), '학교가', '학교');
ok('수업' + eun('수업'), '수업은', '수업');
ok('시간표' + eun('시간표'), '시간표는', '시간표');
ok('수학' + wa('수학'), '수학과', '수학');
ok('기하' + wa('기하'), '기하와', '기하');

console.log('\n=== 이상한 것이 들어와도 안 깨져요 ===');
ok('' + ro(''), '로', '빈 글자');
ok('?' + ro('?'), '?로', '물음표');

console.log(fails.length ? `\n실패 ${fails.length}개\n` + fails.join('\n') : '\n전부 통과');
if (fails.length) Deno.exit(1);
