-- 선생님 시간표를 계정에 담아요.
--
-- NEIS 시간표에는 담당 교사 칸이 아예 없어요. "허유미 선생님 시간표"를
-- 물어볼 방법이 없는 거예요. 그래서 학교 전체 시간표를 받아와서 그 선생님이
-- 맡은 교과군에 해당하는 칸만 골라내요. 지어내는 게 아니라 NEIS에 있는 걸
-- 다시 엮는 거라 정확해요.
--
-- 다만 두 가지는 앱이 알 수 없어요.
--   1. 같은 과목 선생님이 여러 분이면 누가 어느 반인지 몰라요. 수학 선생님이
--      여섯 분이면 여섯 분의 수업이 다 걸려요. 그래서 "내가 들어가는 반"을
--      좁힐 수 있게 해요. 안 좁혀도 쓸 수는 있어요.
--   2. 선택과목 블록은 NEIS가 대표 과목 하나만 적고, 회의나 보강은 애초에
--      NEIS에 없어요. 그래서 칸을 직접 고칠 수 있게 해요.
--
-- 이 둘을 한 칸에 같이 담아요.
--   { "classes": ["2-1", "2-3"], "edits": { "월-6": "2-1 미적분", "화-3": "" } }
--
-- classes 가 비어 있으면 전체예요. edits 의 빈 글자는 "이 칸은 내 수업이
-- 아니에요" 라는 뜻이고, 글자가 있으면 그 내용으로 채워요.
--
-- 기기에 두지 않고 계정에 담는 이유는 교시 바꾸기와 같아요. 한 학기 분량을
-- 손으로 고친 걸 폰 바꿨다고 다시 하라는 건 좀 그래요.
